const LOCAL_STORAGE_KEY = "pgmitra_students_data_v2";

export function getStoredStudents(): Student[] {
  if (typeof window === "undefined") {
    return INITIAL_STUDENTS;
  }

  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(INITIAL_STUDENTS));
      return INITIAL_STUDENTS;
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
    return INITIAL_STUDENTS;
  } catch (err) {
    console.error("Error reading students from localStorage:", err);
    return INITIAL_STUDENTS;
  }
}

export function saveStoredStudents(students: Student[]): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(students));
  } catch (err) {
    console.error("Error saving students to localStorage:", err);
  }
}

export function resetStoredStudents(): Student[] {
  if (typeof window !== "undefined") {
    try {
      localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(INITIAL_STUDENTS));
    } catch {}
  }
  return INITIAL_STUDENTS;
}

export function calculateStudentStats(students: Student[]): StudentStats {
  const totalStudents = students.length;
  const activeStudents = students.filter(
    (s) => s.accountStatus === "ACTIVE" || s.accountStatus === "NOTICE"
  ).length;

  const pendingVerification = students.filter(
    (s) => s.verificationStatus === "PENDING"
  ).length;

  const pendingRentList = students.filter(
    (s) => s.rentStatus === "OVERDUE" || s.rentStatus === "PENDING" || s.rentStatus === "PARTIAL"
  );
  const pendingRentCount = pendingRentList.length;
  const pendingRentAmount = pendingRentList.reduce((acc, s) => acc + (s.rentDueAmount || 0), 0);

  // Vacant room requests / transfers pending
  const vacantRoomRequests = 19; // aggregate available beds across all properties

  // Students leaving soon (either in notice status or leaving in next 20 days)
  const studentsLeavingSoon = students.filter(
    (s) => s.accountStatus === "NOTICE" || (s.accommodation.expectedLeavingDate && isLeavingSoon(s.accommodation.expectedLeavingDate))
  ).length;

  const totalMonthlyCollection = students
    .filter((s) => s.rentStatus === "PAID")
    .reduce((acc, s) => acc + (s.accommodation.monthlyRent || 0), 0);

  return {
    totalStudents,
    activeStudents,
    pendingVerification,
    pendingRentCount,
    pendingRentAmount,
    vacantRoomRequests,
    studentsLeavingSoon,
    totalMonthlyCollection,
  };
}

function isLeavingSoon(dateStr: string): boolean {
  try {
    const target = new Date(dateStr).getTime();
    const now = Date.now();
    const diffDays = (target - now) / (1000 * 60 * 60 * 24);
    return diffDays >= 0 && diffDays <= 20;
  } catch {
    return false;
  }
}

export function exportStudentsToCSV(students: Student[], fileName = "pgmitra_students.csv"): void {
  if (typeof window === "undefined" || !students.length) return;

  const headers = [
    "Student ID",
    "Full Name",
    "Email",
    "Phone",
    "Gender",
    "College",
    "Course",
    "PG / Hostel",
    "Room No",
    "Bed No",
    "Monthly Rent",
    "Security Deposit",
    "Joining Date",
    "Rent Status",
    "Verification Status",
    "Account Status",
  ];

  const rows = students.map((s) => [
    `"${s.studentId}"`,
    `"${s.name}"`,
    `"${s.email}"`,
    `"${s.phone}"`,
    `"${s.gender}"`,
    `"${s.academic.college}"`,
    `"${s.academic.course} - ${s.academic.branch}"`,
    `"${s.accommodation.pgName}"`,
    `"${s.accommodation.roomNumber}"`,
    `"${s.accommodation.bedNumber}"`,
    `"${s.accommodation.monthlyRent}"`,
    `"${s.accommodation.securityDeposit}"`,
    `"${s.accommodation.joiningDate}"`,
    `"${s.rentStatus}"`,
    `"${s.verificationStatus}"`,
    `"${s.accountStatus}"`,
  ]);

  const csvContent = [headers.join(","), ...rows.map((e) => e.join(","))].join("\n");
  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", fileName);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
